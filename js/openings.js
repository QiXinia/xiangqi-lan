// ---------- 局面索引(FEN -> 库内下一着), 供 AI 走定式 ----------
// 同局面同着法可来自多条开局线: 聚合计权, 走法按权重加权随机抽取。
const BOOK = new Map(); // fen -> [{from,to,name,w}]
let maxBookPly = 0;
for (const op of OPENINGS) {
  if (op.book === false || op.fen) continue; // 古谱全局/名局鉴赏仅供打谱, 不入 AI 开局库
  const s = createState();
  const w = op.w || 1; // 主流体系权重略高, 但任何合理首着/分支权重均 >0
  for (let i = 0; i < op.moves.length; i++) {
    const m = parseMove(s, op.moves[i]);
    if (!m) break; // 库着法在该局面不合法, 中止本局索引
    const fen = toFEN(s);
    if (!BOOK.has(fen)) BOOK.set(fen, []);
    const arr = BOOK.get(fen);
    const dup = arr.find(c => c.from[0] === m.from[0] && c.from[1] === m.from[1] && c.to[0] === m.to[0] && c.to[1] === m.to[1]);
    if (dup) dup.w += w; // 同着法权重累加
    else arr.push({ from: m.from, to: m.to, name: op.name, w });
    applyMove(s, m.from, m.to);
    maxBookPly = Math.max(maxBookPly, i + 1);
  }
}

// 命中开局库则返回一着定式(同局面多套定式时按权重加权随机), 否则 null
export function openingBookMove(state, rng = Math.random) {
  if (state.jieqi) return null;
  if (!state.moves || state.moves.length > maxBookPly) return null;
  const arr = BOOK.get(toFEN(state));
  if (!arr || !arr.length) return null;
  let total = 0;
  for (const c of arr) total += (c.w || 1);
  let r = rng() * total, pick = arr[arr.length - 1];
  for (const c of arr) { r -= (c.w || 1); if (r <= 0) { pick = c; break; } }
  return { from: pick.from, to: pick.to, bookName: pick.name };
}

// 判断指定着法是否为开局库定式着(复盘分析时库内着法直接认定为正着)
export function openingHasMove(state, from, to) {
  if (state.jieqi || !state.moves || state.moves.length > maxBookPly) return false;
  const arr = BOOK.get(toFEN(state));
  return !!(arr && arr.some(c => c.from[0] === from[0] && c.from[1] === from[1]
    && c.to[0] === to[0] && c.to[1] === to[1]));
}
